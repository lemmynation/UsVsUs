// Generates supabase/seed-questions.sql from content/packs.json and content/questions/*.json.
// Run `npm run db:seed-sql` after editing questions or packs, then run the SQL in Supabase.
// A unit test fails if the committed SQL is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const dir = join(root, "content", "questions");

export function buildSeedSql(questions, packs = []) {
  const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
  const arr = (xs) => `array[${xs.map(lit).join(", ")}]::text[]`;
  const packRef = (slug) => (slug ? `(select id from packs where slug = ${lit(slug)})` : "null");
  const packRows = packs.map(
    (p) => `  (${lit(p.slug)}, ${lit(p.name)}, ${arr(p.modes)}, ${p.priceMinor}, ${lit(p.currency)}, false, true)`,
  );
  const rows = questions.map(
    (q) =>
      `  (${lit(q.id)}, ${lit(q.gameType)}, ${arr(q.modes)}, ${lit(q.category)}, ${lit(q.intensity)}, ${lit(q.prompt)}, ${lit(JSON.stringify(q.options))}::jsonb, ${q.award ? lit(q.award) : "null"}, ${packRef(q.pack)}, true)`,
  );
  const packSql = packRows.length
    ? `insert into packs (slug, name, mode_scope, price_minor, currency, is_free, active)
values
${packRows.join(",\n")}
on conflict (slug) do update set
  name = excluded.name,
  mode_scope = excluded.mode_scope,
  price_minor = excluded.price_minor,
  currency = excluded.currency,
  is_free = false,
  active = true;

`
    : "";
  return `-- GENERATED by scripts/generate-question-seed.mjs from content/. Do not edit by hand.
-- Safe to re-run: updates existing packs and questions and deactivates questions removed from content.

${packSql}insert into questions (id, game_type, modes, category, intensity, prompt, options, award, pack_id, active)
values
${rows.join(",\n")}
on conflict (id) do update set
  game_type = excluded.game_type,
  modes = excluded.modes,
  category = excluded.category,
  intensity = excluded.intensity,
  prompt = excluded.prompt,
  options = excluded.options,
  award = excluded.award,
  pack_id = excluded.pack_id,
  active = true;

update questions set active = false
where id not in (${questions.map((q) => lit(q.id)).join(", ")});
`;
}

export function loadPacks() {
  return JSON.parse(readFileSync(join(root, "content", "packs.json"), "utf8"));
}

export function loadQuestions() {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .flatMap((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll("\\", "/").split("/").pop())) {
  const out = join(root, "supabase", "seed-questions.sql");
  const questions = loadQuestions();
  writeFileSync(out, buildSeedSql(questions, loadPacks()));
  console.log(`Wrote ${questions.length} questions to supabase/seed-questions.sql`);
}
