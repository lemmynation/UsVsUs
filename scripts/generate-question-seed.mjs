// Generates supabase/seed-questions.sql from content/questions/*.json.
// Run `npm run db:seed-sql` after editing questions, then run the SQL in Supabase.
// A unit test fails if the committed SQL is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const dir = join(root, "content", "questions");

export function buildSeedSql(questions) {
  const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
  const arr = (xs) => `array[${xs.map(lit).join(", ")}]::text[]`;
  const rows = questions.map(
    (q) =>
      `  (${lit(q.id)}, ${lit(q.gameType)}, ${arr(q.modes)}, ${lit(q.category)}, ${lit(q.intensity)}, ${lit(q.prompt)}, ${lit(JSON.stringify(q.options))}::jsonb, true)`,
  );
  return `-- GENERATED by scripts/generate-question-seed.mjs from content/questions/. Do not edit by hand.
-- Safe to re-run: updates existing questions and deactivates ones removed from content.

insert into questions (id, game_type, modes, category, intensity, prompt, options, active)
values
${rows.join(",\n")}
on conflict (id) do update set
  game_type = excluded.game_type,
  modes = excluded.modes,
  category = excluded.category,
  intensity = excluded.intensity,
  prompt = excluded.prompt,
  options = excluded.options,
  active = true;

update questions set active = false
where id not in (${questions.map((q) => lit(q.id)).join(", ")});
`;
}

export function loadQuestions() {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .flatMap((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll("\\", "/").split("/").pop())) {
  const out = join(root, "supabase", "seed-questions.sql");
  const questions = loadQuestions();
  writeFileSync(out, buildSeedSql(questions));
  console.log(`Wrote ${questions.length} questions to supabase/seed-questions.sql`);
}
